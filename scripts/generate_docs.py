"""Generate the docs that are derived from code, so they cannot drift from it.

    python scripts/generate_docs.py          # rewrite the generated files
    python scripts/generate_docs.py --check  # exit 1 if any generated file is stale (used by CI and tests)

Generated: docs/systems.md (from each system's `SystemSpec` and option models), docs/cli.md (from the Typer app),
the system table in README.md between the `<!-- systems:start -->` / `<!-- systems:end -->` markers, and the tool tables
in docs/tools.md between `<!-- tools:start -->` / `<!-- tools:end -->` (from the tool registry).
"""

from __future__ import annotations

import argparse
import re
import sys
import types
import typing
from pathlib import Path
from typing import Any

import typer
from pydantic import BaseModel
from pydantic_core import PydanticUndefined

ROOT = Path(__file__).resolve().parents[1]
README = ROOT / "README.md"
SYSTEMS_MD = ROOT / "docs" / "systems.md"
CLI_MD = ROOT / "docs" / "cli.md"
TOOLS_MD = ROOT / "docs" / "tools.md"
TOOLS_START, TOOLS_END = "<!-- tools:start -->", "<!-- tools:end -->"
START, END = "<!-- systems:start -->", "<!-- systems:end -->"
BANNER = "<!-- Generated by scripts/generate_docs.py from the code. Do not edit by hand. -->"


def _type_label(annotation: Any) -> str:
    origin = typing.get_origin(annotation)
    if origin is typing.Literal:
        return " \\| ".join(f"`{value}`" for value in typing.get_args(annotation))
    if origin in (typing.Union, types.UnionType):
        parts = [_type_label(arg) for arg in typing.get_args(annotation) if arg is not type(None)]
        return " \\| ".join(parts)
    return f"`{getattr(annotation, '__name__', str(annotation))}`"


def _default_label(field: Any) -> str:
    default = field.default
    if default is PydanticUndefined:
        return "*required*"
    if default is None:
        return "unset"
    if isinstance(default, bool):
        return f"`{str(default).lower()}`"
    return f"`{default}`"


def _options_table(model: type[BaseModel]) -> str:
    rows = ["| Option | Type | Default | Description |", "| --- | --- | --- | --- |"]
    for name, field in model.model_fields.items():
        description = (field.description or "").replace("|", "\\|").replace("\n", " ")
        rows.append(f"| `{name}` | {_type_label(field.annotation)} | {_default_label(field)} | {description} |")
    return "\n".join(rows)


def _specs() -> list[Any]:
    from ragbench.rag_systems import all_specs

    return all_specs()


def render_systems_md() -> str:
    from ragbench.config.schema import ChunkerConfig

    specs = _specs()
    lines = [
        "# RAG systems",
        "",
        BANNER,
        "",
        "Every system runs on the same dataset and is configured in the `systems:` list of an experiment file "
        "(see [configuration.md](configuration.md)). Each system accepts `chunker:`, `retrieval:`, `models:` and, where noted, `llm_features:` sections; "
        "unknown options are rejected when the config is loaded.",
        "",
        "Profiles are relative: **cost** `low` = one generation call plus embeddings, `medium` = one extra short LLM call, `high` = several LLM calls per question "
        "or a prompt that carries the whole corpus, or LLM work at ingestion; **latency** `fast` = no LLM call besides generation. *LLM in retrieval* means the retrieval side itself calls an LLM.",
        "",
        "## Overview",
        "",
        "| Type | System | Cost | Latency | LLM in retrieval | Agentic | Best for |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for spec in specs:
        lines.append(
            f"| [`{spec.type}`](#{spec.type}) | {spec.title} | {spec.cost_profile} | {spec.latency_profile} | "
            f"{'yes' if spec.requires_llm else 'no'} | {'yes' if spec.agentic else 'no'} | {spec.best_for} |"
        )
    others = [f"`{spec.type}`" for spec in specs if spec.chunker is not ChunkerConfig]
    lines += ["", "## Chunker options", "", f"All systems except {', '.join(others)} use this `chunker:` section:", "", _options_table(ChunkerConfig), ""]
    for spec in specs:
        lines += [
            f"## `{spec.type}`",
            "",
            f"**{spec.title}.** {spec.summary}.",
            "",
            f"Best for: {spec.best_for}. Cost: {spec.cost_profile}; latency: {spec.latency_profile}.",
            "",
            "`retrieval:` options",
            "",
            _options_table(spec.options) if spec.options.model_fields else "This system has no `retrieval:` options.",
            "",
        ]
        if spec.chunker is None:
            lines += ["This system takes no `chunker:` section.", ""]
        elif spec.chunker is not ChunkerConfig:
            lines += ["`chunker:` options (replaces the shared chunker section)", "", _options_table(spec.chunker), ""]
        if not spec.retrieves:
            lines += ["This system retrieves nothing, so its retrieval columns (recall, MRR, nDCG) are blank in every report, never 0.", ""]
        if spec.llm_features is not None:
            lines += ["`llm_features:` options", "", _options_table(spec.llm_features), ""]
        if spec.supports_tools:
            lines += ["This system accepts a `tools:` list (see [tools.md](tools.md)).", ""]
    return "\n".join(lines).rstrip() + "\n"


def render_readme_table() -> str:
    rows = ["| System | Description | Typical use |", "| --- | --- | --- |"]
    rows += [f"| `{spec.type}` | {spec.summary} | {spec.best_for} |" for spec in _specs()]
    return "\n".join(rows)


def render_readme(text: str) -> str:
    pattern = re.compile(re.escape(START) + r".*?" + re.escape(END), re.S)
    if not pattern.search(text):
        raise SystemExit(f"README.md is missing the {START} ... {END} markers")
    return pattern.sub(lambda _: f"{START}\n{render_readme_table()}\n{END}", text)


def render_tools_block() -> str:
    import ragbench.tools  # noqa: F401  (registers the built-in tools)
    from ragbench.config.schema import ToolsConfig
    from ragbench.registry import TOOLS

    lines = ["| Tool | What it does | Side effects | Tool options |", "| --- | --- | --- | --- |"]
    for name, tool in TOOLS.items():
        options = ", ".join(f"`{option}`" for option in tool.Options.model_fields) or "none"
        lines.append(f"| [`{name}`](#{name}) | {tool.spec.description} | {tool.side_effects} | {options} |")
    lines.append("")
    for name, tool in TOOLS.items():
        lines += [f"#### `{name}`", "", tool.spec.description, "", "Arguments the model passes:", "", _options_table(tool.Args), ""]
        if tool.Options.model_fields:
            lines += ["Options (`tools: [{name: " + name + ", ...}]`):", "", _options_table(tool.Options), ""]
    lines += [
        "#### Run-wide rules (`tools:` section)",
        "",
        _options_table(ToolsConfig),
        "",
        "`evaluation.tools_now` (default `2026-01-01`) is what `date_calc` treats as today for the whole run.",
        "",
    ]
    supporting = [f"[`{spec.type}`](systems.md#{spec.type})" for spec in _specs() if spec.supports_tools]
    lines += ["Systems that accept a `tools:` list: " + (", ".join(supporting) if supporting else "none yet") + "."]
    return "\n".join(lines)


def render_tools_md(text: str) -> str:
    pattern = re.compile(re.escape(TOOLS_START) + r".*?" + re.escape(TOOLS_END), re.S)
    if not pattern.search(text):
        raise SystemExit(f"docs/tools.md is missing the {TOOLS_START} ... {TOOLS_END} markers")
    return pattern.sub(lambda _: f"{TOOLS_START}\n{render_tools_block()}\n{TOOLS_END}", text)


def render_cli_md() -> str:
    from typer.cli import get_docs_for_click
    from typer.main import get_command

    from ragbench.cli import app

    command = get_command(app)
    command.commands = {name: sub for name, sub in command.commands.items() if not getattr(sub, "hidden", False)}  # deprecated aliases are not documented
    context = typer.Context(command, info_name="ragbench")
    body = get_docs_for_click(obj=command, ctx=context, name="ragbench")
    return f"{BANNER}\n\n{body.strip()}\n"


def generated_files() -> dict[Path, str]:
    return {
        SYSTEMS_MD: render_systems_md(),
        CLI_MD: render_cli_md(),
        README: render_readme(README.read_text(encoding="utf-8")),
        TOOLS_MD: render_tools_md(TOOLS_MD.read_text(encoding="utf-8")),
    }


def stale_files() -> list[Path]:
    return [path for path, content in generated_files().items() if not path.exists() or path.read_text(encoding="utf-8") != content]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="do not write; exit 1 if a generated file is out of date")
    args = parser.parse_args(argv)
    if args.check:
        stale = stale_files()
        for path in stale:
            print(f"stale: {path.relative_to(ROOT)}  (run: python scripts/generate_docs.py)", file=sys.stderr)
        return 1 if stale else 0
    for path, content in generated_files().items():
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            path.write_text(content, encoding="utf-8")
            print(f"updated {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
